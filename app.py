@app.route("/super/school/<int:sid>/action", methods=["POST"])
@super_required
def super_school_action(sid):
    action = request.form.get("action")
    with get_db() as db:
        if action == "activate":
            expires = (datetime.now() + timedelta(days=365)).strftime("%Y-%m-%d")
            db.execute("UPDATE schools SET status='active', plan='premium', plan_expires=? WHERE id=?",
                       (expires, sid))
            flash("School activated for 1 year", "success")
        elif action == "suspend":
            db.execute("UPDATE schools SET status='suspended' WHERE id=?", (sid,))
            flash("School suspended", "success")
        elif action == "approve_waiver":
            db.execute("UPDATE schools SET fee_waiver=1, status='active' WHERE id=?", (sid,))
            flash("Fee waiver approved", "success")
        elif action == "deny_waiver":
            db.execute("UPDATE schools SET fee_waiver=0 WHERE id=?", (sid,))
            flash("Fee waiver denied", "success")
        elif action == "delete":
            db.execute("DELETE FROM schools WHERE id=?", (sid,))
            flash("School deleted", "success")
        db.commit()
    return redirect(url_for("super_dashboard"))

