@app.route("/activate", methods=["GET","POST"])
@school_required
def activate():
    """School enters access code to activate/extend subscription."""
    if request.method == "POST":
        code = request.form.get("code","").strip().upper()
        sid  = session["school_id"]
        with get_db() as db:
            ac = db.execute("SELECT * FROM access_codes WHERE code=? AND used=0", (code,)).fetchone()
            if not ac:
                flash("Invalid or already used code. Please check the code and try again.", "error")
                return render_template("activate.html")

            # Calculate expiry
            months  = ac["months"]
            expires = (datetime.now() + timedelta(days=30*months)).strftime("%Y-%m-%d")

            # Update school
            db.execute("""UPDATE schools SET status='active', plan=?, plan_expires=?,
                          access_code=?, code_used=1,
                          fee_waiver=CASE WHEN ? THEN 1 ELSE fee_waiver END
                          WHERE id=?""",
                       (ac["plan"], expires, code,
                        ac["fee_waiver"], sid))

            # Mark code as used
            db.execute("""UPDATE access_codes SET used=1, used_by=?, used_at=?
                          WHERE id=?""",
                       (sid, datetime.now().strftime("%Y-%m-%d %H:%M"), ac["id"]))
            db.commit()

        session["school_status"] = "active"
        flash(f"✅ Activated! Your {ac['plan'].title()} plan is active until {expires}.", "success")
        return redirect(url_for("school_dashboard"))
    return render_template("activate.html")

@app.route("/dashboard")
@school_required
def school_dashboard():
    sid   = session["school_id"]
    today = datetime.now().strftime("%Y-%m-%d")
    dow   = datetime.now().strftime("%A").upper()[:3]
    with get_db() as db:
        school          = db.execute("SELECT * FROM schools WHERE id=?", (sid,)).fetchone()
        total_teachers  = db.execute("SELECT COUNT(*) FROM teachers WHERE school_id=? AND active=1", (sid,)).fetchone()[0]
        scheduled_today = db.execute("SELECT COUNT(*) FROM timetable WHERE school_id=? AND day_of_week=?", (sid,dow)).fetchone()[0]
        checkins_today  = db.execute("SELECT COUNT(*) FROM attendance WHERE school_id=? AND date=?", (sid,today)).fetchone()[0]
        late_today      = db.execute("SELECT COUNT(*) FROM attendance WHERE school_id=? AND date=? AND in_status='LATE'", (sid,today)).fetchone()[0]
        left_early      = db.execute("SELECT COUNT(*) FROM attendance WHERE school_id=? AND date=? AND out_status='LEFT_EARLY'", (sid,today)).fetchone()[0]
        no_checkout     = db.execute("SELECT COUNT(*) FROM attendance WHERE school_id=? AND date=? AND scan_out_time IS NULL", (sid,today)).fetchone()[0]
        avg_dur         = db.execute("SELECT ROUND(AVG(duration_mins),0) FROM attendance WHERE school_id=? AND date=? AND duration_mins IS NOT NULL", (sid,today)).fetchone()[0] or 0
        in_room         = db.execute("""
            SELECT a.*, t.name||' '||t.surname AS teacher_name, r.code AS room_code,
                   p.name AS period_name
            FROM attendance a
            JOIN teachers t ON a.teacher_id=t.id
            JOIN rooms r ON a.room_id=r.id
            LEFT JOIN periods p ON a.period_id=p.id
            WHERE a.school_id=? AND a.date=? AND a.scan_out_time IS NULL
            ORDER BY a.scan_in_time
        """, (sid,today)).fetchall()
        recent = db.execute("""
            SELECT a.*, t.name||' '||t.surname AS teacher_name, r.code AS room_code,
                   p.name AS period_name
            FROM attendance a
            JOIN teachers t ON a.teacher_id=t.id
            JOIN rooms r ON a.room_id=r.id
            LEFT JOIN periods p ON a.period_id=p.id
            WHERE a.school_id=? AND a.date=?
            ORDER BY COALESCE(a.scan_out_time,a.scan_in_time) DESC LIMIT 15
        """, (sid,today)).fetchall()
        missing = db.execute("""
            SELECT tt.*, t.name||' '||t.surname AS teacher_name,
                   r.code AS room_code, p.name AS period_name, p.start_time
            FROM timetable tt
            JOIN teachers t ON tt.teacher_id=t.id
            JOIN rooms r ON tt.room_id=r.id
            JOIN periods p ON tt.period_id=p.id
            WHERE tt.school_id=? AND tt.day_of_week=? AND p.is_break=0
              AND p.end_time <= ?
              AND NOT EXISTS (
                SELECT 1 FROM attendance a
                WHERE a.teacher_id=tt.teacher_id AND a.period_id=tt.period_id AND a.date=?
              )
            ORDER BY p.start_time
        """, (sid, dow, datetime.now().strftime("%H:%M"), today)).fetchall()

    return render_template("dashboard.html",
        school=school, total_teachers=total_teachers,
        scheduled_today=scheduled_today, checkins_today=checkins_today,
        late_today=late_today, left_early=left_early,
        no_checkout=no_checkout, avg_dur=avg_dur,
        in_room=in_room, recent=recent, missing=missing,
        today=today, dow=dow, school_active=_school_active(school))

