@app.route("/attendance")
@school_required
def attendance():
    sid       = session["school_id"]
    today     = datetime.now().strftime("%Y-%m-%d")
    date_from = request.args.get("date_from", today)
    date_to   = request.args.get("date_to",   today)
    t_filter  = request.args.get("teacher_id","")
    s_filter  = request.args.get("in_status","")
    o_filter  = request.args.get("out_status","")

    q = """SELECT a.*, t.name||' '||t.surname AS teacher_name,
                  r.code AS room_code, p.name AS period_name
           FROM attendance a
           JOIN teachers t ON a.teacher_id=t.id
           JOIN rooms r    ON a.room_id=r.id
           LEFT JOIN periods p ON a.period_id=p.id
           WHERE a.school_id=? AND a.date BETWEEN ? AND ?"""
    params = [sid, date_from, date_to]
    if t_filter: q += " AND a.teacher_id=?"; params.append(t_filter)
    if s_filter: q += " AND a.in_status=?";  params.append(s_filter)
    if o_filter: q += " AND a.out_status=?"; params.append(o_filter)
    q += " ORDER BY a.date DESC, a.scan_in_time DESC"

    with get_db() as db:
        records  = db.execute(q, params).fetchall()
        teachers = db.execute("SELECT * FROM teachers WHERE school_id=? AND active=1 ORDER BY surname", (sid,)).fetchall()
        total    = len(records)
        on_time  = sum(1 for r in records if r["in_status"]=="ON_TIME")
        late     = sum(1 for r in records if r["in_status"]=="LATE")
        left_early = sum(1 for r in records if r["out_status"]=="LEFT_EARLY")
        no_out   = sum(1 for r in records if not r["scan_out_time"])
        durs     = [r["duration_mins"] for r in records if r["duration_mins"]]
        avg_dur  = round(sum(durs)/len(durs),0) if durs else 0

        teacher_stats = db.execute("""
            SELECT t.id, t.name||' '||t.surname AS teacher_name,
                   COUNT(*) AS total,
                   SUM(CASE WHEN a.in_status='ON_TIME' THEN 1 ELSE 0 END) AS on_time,
                   SUM(CASE WHEN a.in_status='LATE'    THEN 1 ELSE 0 END) AS late,
                   SUM(CASE WHEN a.out_status='LEFT_EARLY' THEN 1 ELSE 0 END) AS left_early,
                   ROUND(AVG(a.duration_mins),0) AS avg_duration,
                   SUM(CASE WHEN a.in_status='LATE' THEN a.minutes_late ELSE 0 END) AS total_late_mins
            FROM attendance a JOIN teachers t ON a.teacher_id=t.id
            WHERE a.school_id=? AND a.date BETWEEN ? AND ?
            GROUP BY t.id ORDER BY late DESC
        """, (sid, date_from, date_to)).fetchall()

    return render_template("attendance.html",
        records=records, teachers=teachers, teacher_stats=teacher_stats,
        total=total, on_time=on_time, late=late,
        left_early=left_early, no_out=no_out, avg_dur=avg_dur,
        date_from=date_from, date_to=date_to,
        t_filter=t_filter, s_filter=s_filter, o_filter=o_filter)

