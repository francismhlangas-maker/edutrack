@app.route("/timetable/add", methods=["POST"])
@school_required
def add_slot():
    sid         = session["school_id"]
    teacher_id  = request.form["teacher_id"]
    room_id     = request.form["room_id"]
    period_id   = request.form["period_id"]
    subject     = request.form["subject"].strip()
    dow         = request.form["day_of_week"].upper()
    week_type   = request.form.get("week_type","ALL")
    class_code  = request.form.get("class_code","").strip().upper()
    is_split    = 1 if request.form.get("is_split") else 0
    split_group = request.form.get("split_group","").strip()  # e.g. "IsiZulu Group"
    split_label = request.form.get("split_label","").strip()  # e.g. "Language Choice"

    with get_db() as db:
        # ── Clash 1: Teacher in two places at the same time ──────────────────
        # This is ALWAYS a clash — even in splits a teacher can only be in one room
        teacher_clash = db.execute("""
            SELECT tt.*, r.code AS room_code, p.name AS period_name
            FROM timetable tt
            JOIN rooms r   ON tt.room_id=r.id
            JOIN periods p ON tt.period_id=p.id
            WHERE tt.school_id=? AND tt.teacher_id=?
              AND tt.period_id=? AND tt.day_of_week=?
              AND (tt.week_type='ALL' OR ?='ALL' OR tt.week_type=?)
              AND tt.room_id != ?
        """, (sid, teacher_id, period_id, dow,
              week_type, week_type, room_id)).fetchone()

        if teacher_clash:
            t = db.execute("SELECT name,surname FROM teachers WHERE id=?",
                           (teacher_id,)).fetchone()
            flash(f"⛔ TEACHER CLASH: {t['name']} {t['surname']} is already "
                  f"assigned to room {teacher_clash['room_code']} during "
                  f"{teacher_clash['period_name']} on {dow}. "
                  f"A teacher cannot be in two places at once.", "error")
            return redirect(url_for("timetable"))

        # ── Clash 2: Room occupied — but only if NOT a legitimate split ───────
        # A room clash is real only when:
        #   - It's not a split at all, OR
        #   - Both slots are splits but with the same split_group in the same room
        # A room clash is NOT real when:
        #   - Both entries are splits of the same class to different rooms
        #     (e.g. 10A Language A → Zulu Lab, 10A Language B → Sesotho Room)
        room_existing = db.execute("""
            SELECT tt.*, t.name||' '||t.surname AS teacher_name,
                   t.id AS tid
            FROM timetable tt
            JOIN teachers t ON tt.teacher_id=t.id
            WHERE tt.school_id=? AND tt.room_id=?
              AND tt.period_id=? AND tt.day_of_week=?
              AND (tt.week_type='ALL' OR ?='ALL' OR tt.week_type=?)
              AND tt.teacher_id != ?
        """, (sid, room_id, period_id, dow,
              week_type, week_type, teacher_id)).fetchone()

        if room_existing:
            # Determine if this is a legitimate split or a real clash
            # Legitimate: both are splits AND they belong to different split_groups
            both_splits    = is_split and room_existing["is_split"]
            diff_groups    = split_group and room_existing["split_group"] and \
                             split_group != room_existing["split_group"]
            legit_split    = both_splits and diff_groups

            if not legit_split:
                r = db.execute("SELECT code FROM rooms WHERE id=?", (room_id,)).fetchone()
                flash(f"⛔ ROOM CLASH: Room {r['code']} is already occupied by "
                      f"{room_existing['teacher_name']} during this period on {dow}. "
                      f"If this is a class split (e.g. Language groups), "
                      f"tick 'This is a split class' and enter a split group name.", "error")
                return redirect(url_for("timetable"))

        # ── Clash 3: Exact duplicate ──────────────────────────────────────────
        duplicate = db.execute("""
            SELECT id FROM timetable
            WHERE school_id=? AND teacher_id=? AND room_id=?
              AND period_id=? AND day_of_week=?
        """, (sid, teacher_id, room_id, period_id, dow)).fetchone()

        if duplicate:
            flash("⚠️ This exact slot already exists in the timetable.", "error")
            return redirect(url_for("timetable"))

        # ── All clear — save ──────────────────────────────────────────────────
        try:
            db.execute("""
                INSERT INTO timetable
                (school_id,teacher_id,room_id,period_id,subject,
                 day_of_week,week_type,class_code,is_split,split_group,split_label)
                VALUES(?,?,?,?,?,?,?,?,?,?,?)
            """, (sid, teacher_id, room_id, period_id, subject,
                  dow, week_type, class_code, is_split,
                  split_group, split_label))
            db.commit()

            if is_split:
                flash(f"✅ Split slot added — {split_group or subject} "
                      f"({split_label or 'Split class'})", "success")
            else:
                flash("✅ Slot added successfully.", "success")
        except Exception as e:
            flash(f"Error saving slot: {e}", "error")

    return redirect(url_for("timetable"))


@app.route("/timetable/clashes")
@school_required
def check_clashes():
    """Full timetable analysis — clashes, splits, overloads."""
    sid = session["school_id"]
    with get_db() as db:
        # ── Real teacher clashes (same teacher, same period, different rooms) ─
        teacher_clashes = db.execute("""
            SELECT tt.teacher_id, tt.period_id, tt.day_of_week,
                   t.name||' '||t.surname AS teacher_name,
                   p.name AS period_name, p.start_time,
                   GROUP_CONCAT(r.code, ' & ') AS rooms,
                   COUNT(*) AS clash_count
            FROM timetable tt
            JOIN teachers t ON tt.teacher_id=t.id
            JOIN rooms r    ON tt.room_id=r.id
            JOIN periods p  ON tt.period_id=p.id
            WHERE tt.school_id=?
            GROUP BY tt.teacher_id, tt.period_id, tt.day_of_week
            HAVING COUNT(DISTINCT tt.room_id) > 1
            ORDER BY tt.day_of_week, p.start_time
        """, (sid,)).fetchall()

        # ── Real room clashes (same room, same period, different teachers,
        #    but NOT legitimate splits with different group labels) ─────────────
        room_clashes = db.execute("""
            SELECT tt.room_id, tt.period_id, tt.day_of_week,
                   r.code AS room_code,
                   p.name AS period_name, p.start_time,
                   GROUP_CONCAT(t.name||' '||t.surname, ' & ') AS teachers,
                   COUNT(*) AS clash_count,
                   SUM(tt.is_split) AS split_count,
                   COUNT(DISTINCT NULLIF(tt.split_group,'')) AS distinct_groups
            FROM timetable tt
            JOIN rooms r    ON tt.room_id=r.id
            JOIN teachers t ON tt.teacher_id=t.id
            JOIN periods p  ON tt.period_id=p.id
            WHERE tt.school_id=?
            GROUP BY tt.room_id, tt.period_id, tt.day_of_week
            HAVING COUNT(DISTINCT tt.teacher_id) > 1
              -- Only flag if NOT all entries are splits with distinct groups
              AND NOT (
                COUNT(*) = SUM(tt.is_split)
                AND COUNT(DISTINCT NULLIF(tt.split_group,'')) = COUNT(*)
              )
            ORDER BY tt.day_of_week, p.start_time
        """, (sid,)).fetchall()

        # ── Split summary (informational — not a clash) ───────────────────────
        splits_summary = db.execute("""
            SELECT tt.class_code, tt.split_label, tt.period_id,
                   tt.day_of_week, p.name AS period_name, p.start_time,
                   COUNT(*) AS group_count,
                   GROUP_CONCAT(tt.split_group||' ('||r.code||')', ' | ') AS groups
            FROM timetable tt
            JOIN periods p ON tt.period_id=p.id
            JOIN rooms r   ON tt.room_id=r.id
            WHERE tt.school_id=? AND tt.is_split=1 AND tt.class_code != ''
            GROUP BY tt.class_code, tt.split_label, tt.period_id, tt.day_of_week
            ORDER BY tt.class_code, tt.day_of_week, p.start_time
        """, (sid,)).fetchall()

        # ── Overloaded teachers ───────────────────────────────────────────────
        overloaded = db.execute("""
            SELECT t.id, t.name||' '||t.surname AS teacher_name,
                   COUNT(*) AS total_slots
            FROM timetable tt JOIN teachers t ON tt.teacher_id=t.id
            WHERE tt.school_id=?
            GROUP BY t.id HAVING COUNT(*) > 40
            ORDER BY total_slots DESC
        """, (sid,)).fetchall()

        # ── Unassigned teachers ───────────────────────────────────────────────
        unassigned = db.execute("""
            SELECT t.name||' '||t.surname AS teacher_name
            FROM teachers t
            WHERE t.school_id=? AND t.active=1
              AND NOT EXISTS (
                SELECT 1 FROM timetable tt
                WHERE tt.teacher_id=t.id AND tt.school_id=?
              )
            ORDER BY t.surname
        """, (sid, sid)).fetchall()

        total_slots   = db.execute(
            "SELECT COUNT(*) FROM timetable WHERE school_id=?", (sid,)).fetchone()[0]
        total_splits  = db.execute(
            "SELECT COUNT(*) FROM timetable WHERE school_id=? AND is_split=1", (sid,)).fetchone()[0]

    total_clashes = len(teacher_clashes) + len(room_clashes)
    return render_template("clashes.html",
        teacher_clashes=teacher_clashes, room_clashes=room_clashes,
        splits_summary=splits_summary,
        overloaded=overloaded, unassigned=unassigned,
        total_clashes=total_clashes,
        total_slots=total_slots, total_splits=total_splits)

