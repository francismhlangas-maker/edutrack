# ── Helpers ───────────────────────────────────────────────────────────────────
def _hash(pw):
    return hashlib.sha256(pw.encode()).hexdigest()

def _time_to_mins(t):
    h, m = map(int, t.split(":")); return h*60+m

def _generate_code(length=12):
    """Generate a readable access code like EDT-XXXX-XXXX-XXXX."""
    chars = string.ascii_uppercase + string.digits
    chars = chars.replace("0","").replace("O","").replace("I","").replace("1","")
    raw = "".join(secrets.choice(chars) for _ in range(length))
    return f"EDT-{raw[:4]}-{raw[4:8]}-{raw[8:12]}"

def _generate_qr(school_id, room_code, token):
    folder = QR_BASE / str(school_id)
    folder.mkdir(parents=True, exist_ok=True)
    url = f"{PLATFORM_URL}/scan/{token}"
    qr  = qrcode.QRCode(version=1,
                         error_correction=qrcode.constants.ERROR_CORRECT_H,
                         box_size=10, border=4)
    qr.add_data(url)
    qr.make(fit=True)
    img = qr.make_image(fill_color="#1a3c5e", back_color="white")
    img.save(str(folder / f"{room_code}.png"))

def _school_active(school):
    """Check if school subscription is active."""
    if school["status"] != "active":
        return False
    if school["fee_waiver"]:
        return True
    if school["plan_expires"]:
        exp = datetime.strptime(school["plan_expires"], "%Y-%m-%d")
        return exp >= datetime.now()
    return False

