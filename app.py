@app.route("/scan/<token>/action", methods=["POST"])
def scan_action(token):
    with get_db() as db:
        room = db.execute("SELECT r.*, s.name AS school_name FROM rooms r JOIN schools s ON r.school_id=s.id WHERE r.qr_token=?", (token,)).fetchone()
        if not room:
            return jsonify({"success": False, "message": "Invalid QR code."})

        sid        = room["school_id"]
        teacher_id = request.form.get("teacher_id","").strip()
        action     = request.form.get("action","in")

        if not teacher_id:
            return jsonify({"success": False, "message": "Please select your name."})

        teacher = db.execute("SELECT * FROM teachers WHERE id=? AND school_id=?", (teacher_id, sid)).fetchone()
        if not teacher:
            return jsonify({"success": False, "message": "Teacher not found."})

        now     = datetime.now()
        now_str = now.strftime("%H:%M")
        date    = now.strftime("%Y-%m-%d")
        dow     = now.strftime("%A").upper()[:3]
        now_m   = _time_to_mins(now_str)

        period = db.execute("SELECT * FROM periods WHERE school_id=? AND start_time<=? AND end_time>=? ORDER BY start_time LIMIT 1", (sid,now_str,now_str)).fetchone()
        if not period:
            period = db.execute("SELECT * FROM periods WHERE school_id=? AND start_time>? AND is_break=0 ORDER BY start_time LIMIT 1", (sid,now_str)).fetchone()

        # ── SCAN IN ──────────────────────────────────────────────────────────
        if action == "in":
            if period:
                existing = db.execute("SELECT * FROM attendance WHERE school_id=? AND teacher_id=? AND period_id=? AND date=?",
                                      (sid,teacher_id,period["id"],date)).fetchone()
                if existing:
                    msg = "Already completed." if existing["scan_out_time"] else "Already checked in — scan out when you leave."
                    return jsonify({"success": False, "message": msg})

            slot        = None
            in_status   = "UNSCHEDULED"
            mins_late   = 0
            sched_start = sched_end = None

            if period:
                slot = db.execute("SELECT * FROM timetable WHERE school_id=? AND teacher_id=? AND room_id=? AND period_id=? AND day_of_week=?",
                                  (sid,teacher_id,room["id"],period["id"],dow)).fetchone()
                sched_start = period["start_time"]
                sched_end   = period["end_time"]
                mins_late   = now_m - _time_to_mins(sched_start)
                if slot:
                    in_status = "EARLY" if mins_late <= -GRACE_MINUTES else "ON_TIME" if mins_late <= GRACE_MINUTES else "LATE"
                else:
                    in_status = "UNSCHEDULED"

            plen = (_time_to_mins(period["end_time"]) - _time_to_mins(period["start_time"])) if period else None

            db.execute("""INSERT INTO attendance
                (school_id,teacher_id,room_id,period_id,timetable_id,date,day_of_week,
                 scan_in_time,scheduled_start,scheduled_end,in_status,out_status,minutes_late,period_length)
                VALUES(?,?,?,?,?,?,?,?,?,?,?,'PRESENT',?,?)""",
                (sid,teacher_id,room["id"],
                 period["id"] if period else None,
                 slot["id"]   if slot   else None,
                 date,dow,now_str,sched_start,sched_end,in_status,max(0,mins_late),plen))
            db.commit()

            msgs = {
                "EARLY":       ("⏰ Checked In Early!", f"Arrived {abs(mins_late)} min early.", "success"),
                "ON_TIME":     ("✅ Checked In On Time!", f"Signed in at {now_str}.", "success"),
                "LATE":        ("⚠️ Checked In Late", f"{mins_late} min late for {period['name'] if period else 'class'}.", "warning"),
                "UNSCHEDULED": ("📋 Checked In", f"Signed in at {now_str}. No scheduled class found.", "info"),
            }
            title, msg, kind = msgs.get(in_status, ("Recorded","Signed in.","info"))
            return jsonify({"success":True,"action":"in","status":in_status,
                            "title":title,"message":msg,"kind":kind,
                            "teacher":f"{teacher['name']} {teacher['surname']}",
                            "time":now_str,"period":period["name"] if period else "—"})

        # ── SCAN OUT ─────────────────────────────────────────────────────────
        elif action == "out":
            rec = db.execute("""SELECT * FROM attendance
                WHERE school_id=? AND teacher_id=? AND date=? AND scan_out_time IS NULL
                ORDER BY scan_in_time DESC LIMIT 1""", (sid,teacher_id,date)).fetchone()
            if not rec:
                return jsonify({"success":False,"message":"No active check-in found. Please scan in first."})

            dur        = now_m - _time_to_mins(rec["scan_in_time"])
            out_status = "COMPLETED"
            if rec["scheduled_end"]:
                end_m = _time_to_mins(rec["scheduled_end"])
                if now_m < end_m - EARLY_OUT_MINUTES:
                    out_status = "LEFT_EARLY"
                    mins_early = end_m - now_m

            db.execute("UPDATE attendance SET scan_out_time=?,out_status=?,duration_mins=? WHERE id=?",
                       (now_str, out_status, dur, rec["id"]))
            db.commit()

            pname = period["name"] if period else "—"
            if out_status == "LEFT_EARLY":
                title = "⚠️ Left Early"
                msg   = f"Left {end_m-now_m} min before end of {pname}. Time in room: {dur} min."
                kind  = "warning"
            else:
                title = "✅ Checked Out"
                msg   = f"Well done! You taught for {dur} minutes."
                kind  = "success"

            return jsonify({"success":True,"action":"out","status":out_status,
                            "title":title,"message":msg,"kind":kind,
                            "teacher":f"{teacher['name']} {teacher['surname']}",
                            "time_in":rec["scan_in_time"],"time_out":now_str,
                            "duration":dur,"period":pname})

    return jsonify({"success":False,"message":"Unknown action."})

